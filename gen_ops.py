CODE_DIJKSTRA = r'''import heapq

def dijkstra(n, adj, src):
    # adj: list of list of (to, weight), 非负权
    dist = [float("inf")] * n
    dist[src] = 0
    pq = [(0, src)]          # (距离, 节点)
    while pq:
        d, u = heapq.heappop(pq)
        if d > dist[u]:       # 已过期的旧记录，跳过
            continue
        for v, w in adj[u]:
            if dist[u] + w < dist[v]:
                dist[v] = dist[u] + w
                heapq.heappush(pq, (dist[v], v))
    return dist

# 示例：4 个节点，边 0-1(2) 0-2(5) 1-2(1) 2-3(2)
adj = [[(1,2),(2,5)],[(2,1)],[(3,2)],[]]
print(dijkstra(4, adj, 0))   # [0, 2, 3, 5]
'''

CODE_BB = r'''import math

# 0-1 背包 分支定界：价值 v、重量 w、容量 W
def bb_knapsack(v, w, W):
    n = len(v)
    # 按单位价值降序，用于上界估计与分支顺序
    order = sorted(range(n), key=lambda i: v[i]/w[i], reverse=True)
    best = 0
    # 上界：贪心装分数（线性松弛）
    def ub(rem_w, idx, cur):
        if cur + rem_w * (v[order[idx]]/w[order[idx]]) <= best:
            return 0
        space = rem_w
        val = cur
        for i in range(idx, n):
            if w[order[i]] <= space:
                space -= w[order[i]]; val += v[order[i]]
            else:
                val += space * (v[order[i]]/w[order[i]]); break
        return val

    def dfs(idx, rem_w, cur):
        nonlocal best
        if cur > best: best = cur
        if idx == n or rem_w == 0: return
        if ub(rem_w, idx, cur) <= best: return        # 剪枝
        i = order[idx]
        if w[i] <= rem_w:                              # 分支1：选 i
            dfs(idx+1, rem_w - w[i], cur + v[i])
        dfs(idx+1, rem_w, cur)                         # 分支2：不选 i
    dfs(0, W, 0)
    return best

print(bb_knapsack([60,100,120],[10,20,30],50))   # 220
'''

